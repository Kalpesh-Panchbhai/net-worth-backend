package com.networth.networthbackend.entity;

import com.amazonaws.services.dynamodbv2.datamodeling.*;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

@Setter
@Getter
@DynamoDBTable(tableName = "account_transaction")
@AllArgsConstructor
@NoArgsConstructor
public class AccountTransaction {

    @DynamoDBHashKey(attributeName = "id")
    @DynamoDBAutoGeneratedKey
    private String id;

    @DynamoDBAttribute(attributeName = "accountId")
    private String accountId;

    @DynamoDBAttribute(attributeName = "timestamp")
    private String timestamp;

    @DynamoDBAttribute(attributeName = "currentBalance")
    private Double currentBalance;

    @DynamoDBTyped(DynamoDBMapperFieldModel.DynamoDBAttributeType.BOOL)
    @DynamoDBAttribute(attributeName = "paid")
    private Boolean paid;

    @DynamoDBIgnore
    private String operation;
}
