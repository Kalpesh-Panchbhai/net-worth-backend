package com.networth.networthbackend.entity;

import com.amazonaws.services.dynamodbv2.datamodeling.*;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

@Setter
@Getter
@DynamoDBTable(tableName = "account")
@AllArgsConstructor
@NoArgsConstructor
public class Account {

    @DynamoDBHashKey(attributeName = "id")
    @DynamoDBAutoGeneratedKey
    private String id;

    @DynamoDBAttribute(attributeName = "accountType")
    private String accountType;

    @DynamoDBAttribute(attributeName = "loanType")
    private String loanType;

    @DynamoDBAttribute(attributeName = "accountName")
    private String accountName;

    @DynamoDBAttribute(attributeName = "currentBalance")
    private Double currentBalance;

    @DynamoDBTyped(DynamoDBMapperFieldModel.DynamoDBAttributeType.BOOL)
    @DynamoDBAttribute(attributeName = "paymentReminder")
    private Boolean paymentReminder;

    @DynamoDBAttribute(attributeName = "paymentDate")
    private Integer paymentDate;

    @DynamoDBAttribute(attributeName = "currency")
    private String currency;

    @DynamoDBTyped(DynamoDBMapperFieldModel.DynamoDBAttributeType.BOOL)
    @DynamoDBAttribute(attributeName = "active")
    private Boolean active;

    @DynamoDBAttribute(attributeName = "userId")
    private String userId;
}
