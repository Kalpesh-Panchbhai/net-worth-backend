package com.networth.networthbackend.entity;

import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBAttribute;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBAutoGeneratedKey;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBHashKey;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBTable;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

@Setter
@Getter
@DynamoDBTable(tableName = "income")
@AllArgsConstructor
@NoArgsConstructor
public class IncomeEntity {

    @DynamoDBHashKey(attributeName = "id")
    @DynamoDBAutoGeneratedKey
    private String id;

    @DynamoDBAttribute(attributeName = "userId")
    private String userId;

    @DynamoDBAttribute(attributeName = "amount")
    private Double amount;

    @DynamoDBAttribute(attributeName = "taxPaid")
    private Double taxPaid;

    @DynamoDBAttribute(attributeName = "creditedOn")
    private String creditedOn;

    @DynamoDBAttribute(attributeName = "currency")
    private String currency;

    @DynamoDBAttribute(attributeName = "incomeType")
    private String incomeType;

    @DynamoDBAttribute(attributeName = "incomeTag")
    private String incomeTag;
}
